import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium,webkit}=require(process.env.K365_PLAYWRIGHT_MODULE||'@playwright/test');
const base=process.env.K365_QA_URL||'http://127.0.0.1:8799';
const out=`docs/adsense/qa-${process.env.K365_QA_LABEL||'interactions'}`;
await fs.mkdir(out,{recursive:true});
const results=[];
for(const [engine,type] of Object.entries({chromium,webkit})){
 const browser=await type.launch({headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();
 await page.goto(base+'/blogas/',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.editorial-card').count(),20);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 const dismiss=page.locator('#cookie-notice-dismiss');
 if(await dismiss.isVisible())await dismiss.click();
 await page.screenshot({path:`${out}/${engine}-desktop-blog.png`,fullPage:true});
 await page.goto(base+'/paieska/?q='+encodeURIComponent('Kaip atsispausdinti kalendorių'),{waitUntil:'networkidle'});
 const found=page.locator('#site-search-page-results a[href="/blogas/kaip-spausdinti-kalendoriu/"]');
 await found.waitFor({timeout:15000});await found.click();
 await page.waitForURL('**/blogas/kaip-spausdinti-kalendoriu/');
 assert.equal(await page.locator('h1').count(),1);
 const before=await page.locator('h2[id],section[id] h2').first().innerText();
 await page.locator('.editorial-toc a').first().click();
 assert.ok(new URL(page.url()).hash);
 await page.goto(base+'/apie-mus/',{waitUntil:'networkidle'});
 const fish=page.locator('img[src*="/zuvys.svg"]');
 await fish.scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>{const i=document.querySelector('img[src*="/zuvys.svg"]');return i?.complete&&i.naturalWidth>0;});
 await page.goto(base+'/',{waitUntil:'networkidle'});
 await page.emulateMedia({media:'print'});
 const printGuide=await page.locator('[data-editorial-extension]').isVisible();
 assert.equal(printGuide,false,'Editorial help must not print with the personal calendar');
 results.push({engine,desktopWidth:1440,blogCards:20,searchResultOpensArticle:true,articleTocWorks:!!before,previousImageFailureRechecked:true,homeGuideHiddenInPrint:!printGuide});
 await context.close();
 const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
 const plain=await nojs.newPage();await plain.goto(base+'/blogas/kaip-spausdinti-kalendoriu/');
 assert.equal(await plain.locator('h1').count(),1);
 assert.ok((await plain.locator('.editorial-article').innerText()).length>4000);
 results.at(-1).articleReadableWithoutJavaScript=true;
 await nojs.close();await browser.close();
}
await fs.writeFile(`${out}/results.json`,JSON.stringify({base,results},null,2)+'\n');
console.log(JSON.stringify({base,results},null,2));
