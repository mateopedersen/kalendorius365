"""Bundle the canonical JSON sources for the Pages Functions build."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {
    "registry": "site/assets/data/weather-places.json",
    "cityImages": "site/_data/weather_city_images.json",
}


def main():
    # Pages uses a build-time parser that cannot read JS import attributes.
    output = ["// Generated by scripts/weather/pages_data.py from the site's canonical JSON data.\n"]
    for name, source in SOURCES.items():
        document = (ROOT / source).read_text(encoding="utf-8").strip()
        output.append(f"export const {name} = {document};\n")
    (ROOT / "lib/weather-data.mjs").write_text("".join(output), encoding="utf-8")


if __name__ == "__main__":
    main()
